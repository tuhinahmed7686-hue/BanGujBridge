import type { FeedStatus } from '../hooks/useEarthquakeFeed';
import type { FeedSnapshot } from '../types/events';
import { formatDateTime } from '../lib/format';

export const STATUS_LABEL: Record<FeedStatus, string> = {
  loading: 'Connecting to USGS',
  live: 'Connected to USGS',
  stale: 'Stale: refreshes are failing',
  unavailable: 'Unavailable: could not load USGS data',
};

interface Props {
  status: FeedStatus;
  snapshot: FeedSnapshot | null;
  error: string | null;
  failures: number;
  isFetching: boolean;
  shownCount: number;
  intervalSeconds: number;
  onRefresh: () => void;
}

export function DataHealth({ status, snapshot, error, failures, isFetching, shownCount, intervalSeconds, onRefresh }: Props) {
  return (
    <div>
      <dl className="details">
        <dt>Connection</dt>
        <dd><span className={`dot ${status}`} aria-hidden="true" /> {STATUS_LABEL[status]}</dd>
        <dt>Last successful fetch</dt><dd>{snapshot ? formatDateTime(snapshot.fetchedAt) : 'No successful fetch yet'}</dd>
        <dt>Feed generated by USGS</dt><dd>{snapshot ? formatDateTime(snapshot.sourceGeneratedAt) : 'Not available'}</dd>
        <dt>Events received</dt><dd>{snapshot ? snapshot.events.length : 'Not available'}</dd>
        <dt>Events in this view</dt><dd>{snapshot ? shownCount : 'Not available'}</dd>
        {snapshot && snapshot.skippedCount > 0 && (<><dt>Records skipped</dt><dd>{snapshot.skippedCount} (missing or invalid data)</dd></>)}
        <dt>Automatic refresh</dt><dd>Every {intervalSeconds} seconds while this page is open</dd>
      </dl>
      {error && (
        <p className="error" role="alert">
          Latest refresh failed: {error} ({failures} in a row)
        </p>
      )}
      <button className="primary" onClick={onRefresh} disabled={isFetching}>
        {isFetching ? 'Refreshing...' : 'Refresh now'}
      </button>
    </div>
  );
}
